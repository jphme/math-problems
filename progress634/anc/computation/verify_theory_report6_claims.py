def corner_cos(L1, L2, L3):
    """cos of the angle between sides L1, L2 (opposite side L3), exact."""
    return Fr(L1 * L1 + L2 * L2 - L3 * L3, 2 * L1 * L2)


def addition_hypothesis(L1, L2, L3, e1, e2, e3):
    """Check: L1/e1, L2/e2 integers; corner angle between L1,L2 equals the tile angle
    between e1,e2 or its supplement; and the fundamental cell (e1,e2) splits along the
    correct diagonal into two triangles congruent to (e1,e2,e3). Returns (ok, ratios)."""
    if L1 % e1 or L2 % e2:
        return False, None
    ct = corner_cos(L1, L2, L3)
    ctile = corner_cos(e1, e2, e3)
    if ct == ctile:
        # diagonal opposite the corner: f^2 = e1^2+e2^2-2 e1 e2 cos = e3^2 by construction
        f2 = Fr(e1 * e1 + e2 * e2) - 2 * e1 * e2 * ct
        return f2 == e3 * e3, (L1 // e1, L2 // e2)
    if ct == -ctile:
        # supplement: the cell has angles (theta, pi-theta); the OTHER diagonal splits it
        # into triangles with included angle pi-theta = tile angle: f^2 with cos = -ct
        f2 = Fr(e1 * e1 + e2 * e2) - 2 * e1 * e2 * (-ct)
        return f2 == e3 * e3, (L1 // e1, L2 // e2)
    return False, None


