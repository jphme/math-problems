def is_square(n):
    if n < 0:
        return False
    r = isqrt(n)
    return r * r == n


def is_sum_two_squares(n):
    # n = sum of two squares iff every prime p = 3 (mod 4) divides n to an even power
    if n < 0:
        return False
    m, p = n, 2
    while p * p <= m:
        if m % p == 0:
            e = 0
            while m % p == 0:
                m //= p
                e += 1
            if p % 4 == 3 and e % 2 == 1:
                return False
        p += 1
    return not (m % 4 == 3)


def classical(N):
    if is_square(N) or is_sum_two_squares(N):
        return True
    for k in (2, 3, 6):
        if N % k == 0 and is_square(N // k):
            return True
    return False


def in_semigroup(x, gens):
    if x < 0:
        return False
    reach = [False] * (x + 1)
    reach[0] = True
    for i in range(1, x + 1):
        reach[i] = any(g <= i and reach[i - g] for g in gens)
    return reach[x]


def semigroup_solutions(x, gens):
    """All (n_1,...,n_k) >= 0 with sum n_i * gens[i] = x."""
    sols = []

    def rec(i, rem, acc):
        if i == len(gens) - 1:
            if rem % gens[i] == 0:
                sols.append(tuple(acc + [rem // gens[i]]))
            return
        g = gens[i]
        for n in range(rem // g + 1):
            rec(i + 1, rem - n * g, acc + [n])

    rec(0, x, [])
    return sorted(sols)


