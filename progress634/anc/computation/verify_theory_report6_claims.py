def g2a_first_layer_status(u, v, r):
    """Config-by-config first-layer feasibility given forced P_v corner patches.
    Returns dict config -> alive(bool). Type B: c-side on the equal side; C: c-side on base."""
    a, b, cc = u * u, v * v - u * u, u * v
    SG = [a, b, cc]
    leg, base = u * b * r, v * b * r
    E_B = leg - v * cc            # = u(rb - v^2)
    legC = leg - v * b            # = b(ur - v), C-corner leg residual (auto in SG if >= 0)
    out = {}
    # BB: both patches put b on the base: base residual vbr - 2vb = vb(r-2) (auto if r>=2)
    out["BB"] = (E_B >= 0 and in_semigroup(E_B, SG) and r >= 2)
    # BC: one of each
    R_BC = base - v * b - v * cc  # = v((r-1)b - uv)
    out["BC"] = (E_B >= 0 and in_semigroup(E_B, SG) and legC >= 0
                 and R_BC >= 0 and in_semigroup(R_BC, SG))
    # CC: both c-sides on the base
    R_CC = base - 2 * v * cc      # = v(rb - 2uv)
    out["CC"] = (legC >= 0 and R_CC >= 0 and in_semigroup(R_CC, SG))
    return out, E_B, R_BC, R_CC


